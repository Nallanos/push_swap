#include "libft.h"

char	*ft_strnstr(const char *big, const char *little, size_t len)
{
	size_t	i;
	size_t	j;

	i = 0;
	if (little[i] == '\0')
		return ((char *)big);
	while (i < len && big[i])
	{
		j = 0;
		while (little[j] == big[i + j] && little[j])
			++j;
		if (j == ft_strlen(little) && j + i <= len)
			return ((char *)big + i);
		++i;
	}
	return (NULL);
}
